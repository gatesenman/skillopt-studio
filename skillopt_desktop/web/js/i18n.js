// Safe storage: some embedded webviews (e.g. WebKit2GTK under pywebview)
// expose `localStorage` as `null`, so a bare access throws and breaks boot.
const _mem = {};
function storeGet(k) {
  try { if (window.localStorage) return window.localStorage.getItem(k); } catch { /* ignore */ }
  return k in _mem ? _mem[k] : null;
}
function storeSet(k, v) {
  _mem[k] = v;
  try { if (window.localStorage) window.localStorage.setItem(k, v); } catch { /* ignore */ }
}

let lang = storeGet("skillopt_lang") || "zh";

export function getLang() { return lang; }

export function setLang(l) {
  lang = STR[l] ? l : "zh";
  storeSet("skillopt_lang", lang);
  if (typeof document !== "undefined") document.documentElement.lang = lang;
}

export function t(key) {
  const d = STR[lang] || STR.zh;
  return d[key] ?? STR.zh[key] ?? key;
}
